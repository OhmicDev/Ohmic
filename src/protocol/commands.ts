export type CommandId = (typeof COMM)[keyof typeof COMM]

const NAMES = new Map<number, string>(Object.entries(COMM).map(([k, v]) => [v, k]))

export function commandName(id: number): string {
  return NAMES.get(id) ?? `UNKNOWN_${id}`
}

export const HW_TYPE = {
  VESC: 0,
  VESC_BMS: 1,
  CUSTOM_MODULE: 2,
} as const

export function hwTypeLabel(t: number): string {
  switch (t) {
    case HW_TYPE.VESC:
      return 'Motor controller'
    case HW_TYPE.VESC_BMS:
      return 'Battery management system'
    case HW_TYPE.CUSTOM_MODULE:
      return 'Custom module'
    default:
      return `Unknown (${t})`
  }
}
